#!/bin/bash
set -euo pipefail
project_root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$project_root"
scratch_path="${BOTCLIENT_SCRATCH_PATH:-$project_root/.build/app}"
swift build -c release --arch arm64 --scratch-path "$scratch_path"
binary_dir="$(swift build -c release --arch arm64 --scratch-path "$scratch_path" --show-bin-path)"
app_path="${BOTCLIENT_APP_PATH:-$project_root/dist/MOS.app}"
mkdir -p "$app_path/Contents/MacOS" "$app_path/Contents/Resources"
cp "$binary_dir/BotClient" "$app_path/Contents/MacOS/BotClient"
cp Support/Info.plist "$app_path/Contents/Info.plist"
cp Support/AvatarArtwork.json "$app_path/Contents/Resources/AvatarArtwork.json"
cp Support/BrandLogo.png "$app_path/Contents/Resources/BrandLogo.png"
mkdir -p "$app_path/Contents/Resources/Fonts"
cp Support/Fonts/* "$app_path/Contents/Resources/Fonts/"
swift Scripts/make-icon.swift "$scratch_path"
iconutil -c icns "$scratch_path/AppIcon.iconset" -o "$app_path/Contents/Resources/AppIcon.icns"
codesign --force --sign - "$app_path"
codesign --verify --deep --strict "$app_path"
printf '%s\n' "$app_path"
